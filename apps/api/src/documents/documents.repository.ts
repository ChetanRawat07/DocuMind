import { type DocumentStatus, type DocumentType, MAX_DOCUMENT_PAGE_SIZE } from '@documind/shared';
import { Inject, Injectable } from '@nestjs/common';
import type { Selectable } from 'kysely';
import { DATABASE } from '../database/database.module.js';
import type { DatabaseExecutor } from '../database/database.types.js';
import type { Documents } from '../database/generated/database.js';

export interface Document {
  readonly id: string;
  readonly ownerId: string;
  readonly originalFilename: string;
  readonly mimeType: string;
  readonly sizeBytes: number;
  readonly storageKey: string;
  readonly documentType: DocumentType | null;
  readonly status: DocumentStatus;
  readonly processedAt: Date | null;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

export interface NewDocument {
  /** Generated by the caller, because the storage key embeds the document id. */
  readonly id: string;
  readonly ownerId: string;
  readonly originalFilename: string;
  readonly mimeType: string;
  readonly sizeBytes: number;
  readonly storageKey: string;
}

/** Position after the last item of a page; documents are ordered newest first. */
export interface DocumentPageCursor {
  readonly createdAt: Date;
  readonly id: string;
}

export interface DocumentPage {
  readonly items: readonly Document[];
  readonly nextCursor: DocumentPageCursor | null;
}

/**
 * Every read and delete takes the owner's id and filters on it in SQL, so a
 * caller cannot fetch another user's document by guessing its id (IDOR).
 */
@Injectable()
export class DocumentsRepository {
  constructor(@Inject(DATABASE) private readonly db: DatabaseExecutor) {}

  async create(document: NewDocument, executor = this.db): Promise<Document> {
    const row = await executor
      .insertInto('documents')
      .values({
        id: document.id,
        user_id: document.ownerId,
        original_filename: document.originalFilename,
        mime_type: document.mimeType,
        size_bytes: document.sizeBytes,
        storage_key: document.storageKey,
      })
      .returningAll()
      .executeTakeFirstOrThrow();
    return toDocument(row);
  }

  async findByIdForOwner(
    ownerId: string,
    documentId: string,
    executor = this.db,
  ): Promise<Document | null> {
    const row = await executor
      .selectFrom('documents')
      .selectAll()
      .where('id', '=', documentId)
      .where('user_id', '=', ownerId)
      .executeTakeFirst();
    return row ? toDocument(row) : null;
  }

  /**
   * Keyset pagination, newest first. `WHERE (created_at, id) < cursor` walks
   * the (user_id, created_at DESC, id DESC) index directly, so page 1000 costs
   * the same as page 1, and rows inserted meanwhile never shift page borders
   * the way OFFSET does. The id tiebreaker handles equal timestamps.
   */
  async listForOwner(
    ownerId: string,
    page: { readonly limit: number; readonly after?: DocumentPageCursor },
    executor = this.db,
  ): Promise<DocumentPage> {
    if (!Number.isInteger(page.limit) || page.limit < 1 || page.limit > MAX_DOCUMENT_PAGE_SIZE) {
      throw new RangeError(`limit must be an integer between 1 and ${MAX_DOCUMENT_PAGE_SIZE}`);
    }

    let query = executor.selectFrom('documents').selectAll().where('user_id', '=', ownerId);
    const { after } = page;
    if (after) {
      query = query.where((eb) =>
        eb(eb.refTuple('created_at', 'id'), '<', eb.tuple(after.createdAt, after.id)),
      );
    }

    // Fetch one extra row to learn whether another page exists.
    const rows = await query
      .orderBy('created_at', 'desc')
      .orderBy('id', 'desc')
      .limit(page.limit + 1)
      .execute();

    const items = rows.slice(0, page.limit).map(toDocument);
    const last = items.at(-1);
    const hasMore = rows.length > page.limit;
    return {
      items,
      nextCursor: hasMore && last ? { createdAt: last.createdAt, id: last.id } : null,
    };
  }

  /**
   * Deletes the document row; its jobs and extractions cascade. Returns the
   * deleted document (the caller needs its storage key) or null if the owner
   * has no such document.
   */
  async deleteForOwner(
    ownerId: string,
    documentId: string,
    executor = this.db,
  ): Promise<Document | null> {
    const row = await executor
      .deleteFrom('documents')
      .where('id', '=', documentId)
      .where('user_id', '=', ownerId)
      .returningAll()
      .executeTakeFirst();
    return row ? toDocument(row) : null;
  }
}

function toDocument(row: Selectable<Documents>): Document {
  return {
    id: row.id,
    ownerId: row.user_id,
    originalFilename: row.original_filename,
    mimeType: row.mime_type,
    sizeBytes: row.size_bytes,
    storageKey: row.storage_key,
    // CHECK constraints guarantee these values; a database test keeps them in
    // sync with the shared constants.
    documentType: row.document_type as DocumentType | null,
    status: row.status as DocumentStatus,
    processedAt: row.processed_at,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}
